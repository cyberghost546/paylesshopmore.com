PG_DUMP_PATH = os.environ.get("PG_DUMP_PATH", "pg_dump")


# ---------------------------------------------------------------------------
# Cache
# ---------------------------------------------------------------------------

# Django's default cache is per-process memory, which is fine until the site
# runs more than one worker — and then it quietly breaks throttling, because
# each worker counts requests in its own copy and the real limit becomes the
# configured rate times the number of processes.
#
# It also forgets on purpose: it holds 300 entries and drops a third of them
# when full. The sign-in lockout and the reset-mail cap (accounts/lockout.py)
# live in the cache too, and anybody who can make the site remember 300 junk
# usernames could wipe the count against the one account they are guessing.
#
# So: Redis when there is one. Without it, a deployed site keeps the cache in
# its own Postgres - shared by every process, and with a ceiling high enough
# that culling never reaches the counters that matter - and a development
# checkout keeps per-process memory, so a fresh clone runs with nothing
# installed. The database table is made by `createcachetable`, which
# entrypoint.sh runs on every start (it does nothing when the table exists).
REDIS_URL = os.environ.get("REDIS_URL", "")
CACHE_TABLE = "django_cache"

if REDIS_URL:
    CACHES = {
        'default': {
            'BACKEND': 'django.core.cache.backends.redis.RedisCache',
            'LOCATION': REDIS_URL,
        }
    }
elif not DEBUG:
    CACHES = {
        'default': {
            'BACKEND': 'django.core.cache.backends.db.DatabaseCache',
            'LOCATION': CACHE_TABLE,
            'OPTIONS': {'MAX_ENTRIES': 1_000_000},
        }
    }
else:
    CACHES = {
        'default': {
            'BACKEND': 'django.core.cache.backends.locmem.LocMemCache',
            'LOCATION': 'paylesshopmore-local',
        }
    }


